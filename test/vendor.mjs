#!/usr/bin/env node
/**
 * Suite: the vendored am bundle is the file we think it is.
 *
 * `am.mjs` is upstream-generated and committed here, so the two properties worth
 * guarding are: it still matches its manifest (nothing hand-edited it), and the
 * version it reports is the version we pinned. The rest of the repo builds its
 * whole product on top of this file, and a silently-different vendor copy fails
 * somewhere far away from the cause.
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..");
const dir = path.join(root, "vendor", "am");

let passed = 0;
const failures = [];
function check(name, cond, extra) {
  if (cond) passed++;
  else failures.push(name);
  console.log(`${cond ? "PASS" : "FAIL"}  ${name}${extra != null ? "  " + extra : ""}`);
}

const manifest = JSON.parse(fs.readFileSync(path.join(dir, "manifest.json"), "utf8"));
const bundle = fs.readFileSync(path.join(dir, manifest.file));

check("manifest pins a version", typeof manifest.version === "string" && /^\d+\.\d+\.\d+$/.test(manifest.version), manifest.version);
check("manifest pins a sha256", /^[0-9a-f]{64}$/.test(manifest.sha256));
check("am.mjs matches the recorded size", bundle.length === manifest.bytes, `${bundle.length} vs ${manifest.bytes}`);
check("am.mjs matches the recorded sha256", createHash("sha256").update(bundle).digest("hex") === manifest.sha256);
check("bundle still carries the upstream 'do not edit' header", bundle.subarray(0, 400).toString("utf8").includes("generated by scripts/build.mjs, do not edit"));
check("MIT license ships next to the copy", fs.readFileSync(path.join(dir, "LICENSE"), "utf8").includes("MIT License"));
check("check-vendor.mjs passes on its own", (() => {
  try {
    execFileSync(process.execPath, [path.join(root, "scripts", "check-vendor.mjs")], { stdio: "pipe" });
    return true;
  } catch {
    return false;
  }
})());

const reported = execFileSync(process.execPath, [path.join(dir, manifest.file), "--version"], { encoding: "utf8" }).trim();
check("am --version equals the pinned version", reported === manifest.version, `reported ${reported}`);

const list = execFileSync(process.execPath, [path.join(dir, manifest.file), "list"], { encoding: "utf8" });
check("am list advertises the components the docs name", ["flow", "sequence", "timeline", "kv", "callout", "ask", "tree"].every((c) => list.includes(c)));

// engines.node is >=20 because am.mjs calls Array.prototype.toSorted (V8 11 / Node 20).
// This assertion is the *reason* recorded as a test: if upstream ever drops toSorted the
// floor can come back down, and if somebody lowers engines.node this suite says so.
const pkg = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
check("bundle uses toSorted", bundle.subarray(0, 575_084).toString("utf8").includes(".toSorted("));
check("package.json engines is >=20", />=\s*2\d/.test(pkg.engines?.node || ""), pkg.engines?.node);

console.log(`\n${passed} passed, ${failures.length} failed`);
process.exit(failures.length ? 1 : 0);
