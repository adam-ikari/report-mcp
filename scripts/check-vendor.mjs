#!/usr/bin/env node
/**
 * Vendor drift gate: `vendor/am/am.mjs` must be exactly the file `manifest.json` describes.
 *
 * Runs from `prepare` (install time) and from CI. Zero dependencies on purpose — at `prepare`
 * the package's devDependencies may not be installed yet — and it never shells out to am: an
 * integrity check must not depend on the thing it is checking being runnable.
 */
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "vendor", "am");
const manifestPath = path.join(dir, "manifest.json");
const filePath = path.join(dir, "am.mjs");
const licensePath = path.join(dir, "LICENSE");

function die(msg) {
  console.error(`[check-vendor] ${msg}`);
  process.exit(1);
}

let manifest;
try {
  manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
} catch (err) {
  die(`cannot read ${path.relative(process.cwd(), manifestPath)}: ${err.message}`);
}

if (!fs.existsSync(filePath)) die(`vendor/am/${manifest.file} is missing`);

const buf = fs.readFileSync(filePath);
const sha256 = createHash("sha256").update(buf).digest("hex");
if (buf.length !== manifest.bytes) {
  die(`size drift: am.mjs is ${buf.length} bytes, manifest says ${manifest.bytes}`);
}
if (sha256 !== manifest.sha256) {
  die(`checksum mismatch: got ${sha256}, manifest says ${manifest.sha256}`);
}

// The upstream bundle is generated and says so in its second line. If that line is gone,
// somebody edited the vendor copy — the sha256 above would already have caught it, but this
// names the failure instead of leaving a hash to interpret.
const header = buf.subarray(0, 400).toString("utf8");
if (!header.includes("generated by scripts/build.mjs, do not edit")) {
  die("am.mjs no longer carries the upstream 'do not edit' header — is it still the generated bundle?");
}

if (!fs.existsSync(licensePath)) die("vendor/am/LICENSE is missing (MIT text must ship with the copy)");
if (!fs.readFileSync(licensePath, "utf8").includes("MIT License")) die("vendor/am/LICENSE is not the MIT text");

console.log(`[check-vendor] am.mjs ${manifest.version} · ${sha256.slice(0, 12)}… · ${manifest.bytes} bytes`);
