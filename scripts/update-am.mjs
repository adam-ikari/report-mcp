#!/usr/bin/env node
/**
 * Replace the vendored am CLI and re-record its manifest:
 *
 *   node scripts/update-am.mjs --from <url|path> <new-version>
 *
 * The version argument is not cosmetic — it is checked against the output of
 * `node am.mjs --version`, so a copy-paste of the wrong tag fails here rather than at runtime.
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "vendor", "am");
const filePath = path.join(dir, "am.mjs");
const manifestPath = path.join(dir, "manifest.json");

const argv = process.argv.slice(2);
const fromIdx = argv.indexOf("--from");
const from = fromIdx >= 0 ? argv[fromIdx + 1] : null;
const version = argv.filter((a, i) => !a.startsWith("--") && i !== fromIdx + 1)[0];

if (!from || !version) {
  console.error("usage: node scripts/update-am.mjs --from <url|path> <version>");
  process.exit(2);
}

const bundle = from.match(/^https?:\/\//)
  ? Buffer.from(await (await fetch(from)).arrayBuffer())
  : fs.readFileSync(from);

if (bundle.length < 400_000) {
  console.error(`refusing: ${bundle.length} bytes is not the am bundle (expected ~575 kB)`);
  process.exit(1);
}
const header = bundle.subarray(0, 400).toString("utf8");
if (!header.includes("generated by scripts/build.mjs, do not edit")) {
  console.error("refusing: no upstream 'generated … do not edit' header");
  process.exit(1);
}

fs.writeFileSync(filePath, bundle, { mode: 0o755 });

// Run it before recording the manifest: if the new bundle cannot start, nothing gets pinned.
const reported = execFileSync(process.execPath, [filePath, "--version"], { encoding: "utf8" }).trim();
if (reported !== version) {
  console.error(`refusing: --version reports ${reported}, requested ${version}`);
  process.exit(1);
}

const before = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, "utf8")) : {};
const manifest = {
  name: "answer-me-with-html",
  version,
  file: "am.mjs",
  bytes: bundle.length,
  sha256: createHash("sha256").update(bundle).digest("hex"),
  license: "MIT",
  source: before.source || "https://github.com/QingYunA/answer-me-with-html",
  upstreamPath: before.upstreamPath || "skills/answer-me-with-html/scripts/am.mjs",
  vendoredAt: new Date().toISOString().slice(0, 10),
  node: ">=20",
};
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n");

console.log(
  `am ${before.version || "?"} → ${version} · ${(before.bytes || 0)} → ${bundle.length} bytes\n` +
    `sha256 ${manifest.sha256}\n` +
    `next: npm test (test/am-smoke.mjs renders a real page with the new bundle)`,
);
