#!/usr/bin/env node
/**
 * Render examples/*.md into docs/public/reports/ with the vendored am.
 *
 * This is the vendor's usability gate: if an example page cannot be generated from an
 * example draft, the vendored bundle is broken. `--check` renders into a temp dir and
 * fails on any difference from the committed pages, so CI stays honest about drift
 * without a second renderer to keep in sync.
 */
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const AM = path.join(REPO, "vendor", "am", "am.mjs");
const DRAFTS = path.join(REPO, "examples");
const OUT = path.join(REPO, "docs", "public", "reports");
const CHECK = process.argv.includes("--check");

/**
 * am writes `Generated by … 0.5.0 · 2026-10-10 14:03 ·` into the page footer.
 * Everything else in a page is a pure function of the draft, so the gate compares
 * with that one timestamp normalised out — otherwise CI fails on the clock.
 */
const unstamped = (s) => s.replace(/· \d{4}-\d{2}-\d{2} \d{2}:\d{2} ·/g, " · ");

if (!fs.existsSync(AM)) {
  console.error(`the vendored renderer is missing at ${AM}`);
  process.exit(1);
}

const scratch = fs.mkdtempSync(path.join(os.tmpdir(), "report-mcp-samples-"));
let failed = 0;

for (const name of fs.readdirSync(DRAFTS).filter((f) => f.endsWith(".md")).sort()) {
  const draft = path.join(DRAFTS, name);
  const target = path.join(OUT, name.replace(/\.md$/, ".html"));
  const out = CHECK ? path.join(scratch, path.basename(target)) : target;
  fs.mkdirSync(path.dirname(out), { recursive: true });

  const res = spawnSync(process.execPath, [AM, "render", draft, "--no-open", "-o", out], {
    encoding: "utf8",
    // Relative src= and image paths in a draft name files next to it.
    cwd: DRAFTS,
    env: {
      ...process.env,
      AM_HOME: path.join(scratch, "am-home"),
      AM_NO_OPEN: "1",
      AM_NO_UPDATE_CHECK: "1",
    },
    timeout: 30000,
  });

  if (res.status !== 0) {
    console.error(`FAIL  ${name}\n${res.stdout || ""}${res.stderr || ""}`);
    failed++;
    continue;
  }

  if (CHECK) {
    const committed = fs.existsSync(target) ? unstamped(fs.readFileSync(target, "utf8")) : "";
    const fresh = unstamped(fs.readFileSync(out, "utf8"));
    if (!committed || committed !== fresh) {
      console.error(`DRIFT ${name} -> ${path.relative(REPO, target)} is not what the draft renders to`);
      failed++;
      continue;
    }
  }
  console.log(`ok    ${path.basename(target)}  ${fs.statSync(out).size} bytes`);
}

fs.rmSync(scratch, { recursive: true, force: true });
if (failed) {
  console.error(`\n${failed} example(s) failed`);
  process.exit(1);
}
console.log(CHECK ? "\nall example pages match their drafts" : `\nwrote example pages to ${path.relative(REPO, OUT)}/`);
