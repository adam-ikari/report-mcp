#!/usr/bin/env node
/**
 * Bake the panel into the Worker as string constants.
 *
 * ## Why the Worker serves the panel itself
 *
 * The obvious Workers-Static-Assets setup is `assets = { directory, binding }`
 * plus a Worker handling `/api/*`. It cannot be tested here: Miniflare 4
 * answers an asset miss with its own 404 and **never calls the Worker**, so every
 * `/api` route and the token-gated shell would be unreachable in tests while
 * working in production. Testing one thing and deploying another is exactly the
 * failure mode this project keeps getting bitten by, so the Worker owns its own
 * static files and there is a single code path.
 *
 * The cost is that the mirror serves the panel version it was deployed with, so a
 * front-end change needs a Worker deploy to show up remotely. That is the right
 * trade: the mirror is a mirror, and the local panel still updates on its own.
 *
 * ## Generated, not committed
 *
 * Same rule as `public/demo-data.js`: it is a build output, so it is not tracked
 * and CI's drift gate does not cover it. `npm run build` regenerates it.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..");
const out = path.join(root, "worker", "src", "panel-assets.ts");

const shellPath = path.join(root, "public", "index.html");
const bundlePath = path.join(root, "public", "panel.js");

if (!fs.existsSync(shellPath) || !fs.existsSync(bundlePath)) {
  console.error("public/index.html or public/panel.js is missing — run `npm run build` first.");
  process.exit(1);
}

const shell = fs.readFileSync(shellPath, "utf8");
const bundle = fs.readFileSync(bundlePath, "utf8");

// The bundle is one very long line; wrapping it would change nothing semantically
// and would make the generated file unreviewable anyway.
const body = `/* GENERATED by scripts/build-worker-assets.mjs — do not edit, do not commit. */
export const SHELL_HTML = ${JSON.stringify(shell)};
export const PANEL_JS = ${JSON.stringify(bundle)};
`;

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, body, "utf8");
console.log(
  `wrote ${path.relative(root, out)}  shell ${(shell.length / 1024).toFixed(1)} kB + bundle ${(bundle.length / 1024).toFixed(1)} kB`,
);
